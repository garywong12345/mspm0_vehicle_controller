//** This template project has all initializations required to both control the motors
//** via PWM and measure the speed of the motors. The PWM is configured using a 40 kHz
//** period (800 counts). The motors are initialized to be DISABLED and in FORWARD mode.
//** The encoders measurements are stored within the variables enc_counts_avg_L and 
//** enc_counts_avg_R for the left and right motors, respectively. A maximum value for
//** enc_counts_avg_{} is enforced to be 2e6 such that when the wheel stops, a reasonable 
//** value for the encoders exists: a very large number that can be assumed to be stopped.
//** Finally, a third timer is added to measure a 100 ms period for control system
//** timing. The variable runControl is set to 1 each period and then reset in the main.
//**
//** PWM generated by TIMG8 CCR0: Right Wheel, CCR1: Left Wheel
//** Encoders measured by TIMG6 CCR0: Left Wheel, CCR1: Right Wheel
//** 100ms Timing generated by TIMG0

