// START Variables copied from Lab 3
uint32_t enc_total_events_L,enc_total_events_R;
int32_t enc_counts_track_L,enc_counts_track_R;
int32_t enc_counts_L,enc_counts_R;
uint8_t enc_flag_L,enc_flag_R;
uint32_t enc_counts_sum_L,enc_counts_sum_R; // Use to sum for averaging
uint8_t enc_events_sum_L,enc_events_sum_R; // Used to track averaging
uint32_t enc_counts_avg_L,enc_counts_avg_R; // enc_counts average over 6 
uint16_t leftCCR = 80;  // 80 corresponds to a 10% duty cycle
uint16_t rightCCR = 80; // Max CCR = 720. 90% DC
float Ki = 0.01; // Integral factor
float Kp = 0.9;
float LeftIntegral = 0.0f;
float RightIntegral = 0.0f;
uint8_t stop = 0;

// END Variables copied from Lab 3

bool flag_100ms = 0;



int main() {      /// Main Function ///
  
    sysInit();
    GPIOInit();
    timerInit();
    ADCInit();

    while(1) {  
        if(flag_100ms){
            ADC_startConversion(ADC0);
            while (ADC_getStatus(ADC0)) {}

            uint16_t adc0_val   = ADC_getResult(ADC0, ADC_MEM_INDEX_0);
            uint16_t adc0_steer = ADC_getResult(ADC0, ADC_MEM_INDEX_1);

            // Speed command: -50 to +50
            float desired_speed = (((float)adc0_val - 2048.0f) / 2048.0f) * 50.0f;  // CCR % Units

            if (desired_speed > 50.0f) {    //  Limits
                desired_speed = 50.0f;
            } else if (desired_speed < -50.0f) {
                desired_speed = -50.0f;
            } else if (fabsf(desired_speed) < 10.0f) {
                desired_speed = 0.0f;
            }

            // Steering command: normalize to about -1 to +1
            float steer = (((float)adc0_steer - 2048.0f) / 2048.0f);

            // Dead zone around center
            if (fabsf(steer) < 0.15f) {
                steer = 0.0f;
            }

            // Max differential speed from your lab calculation
            float delta_v = steer * 17.5f;

            // Flip turning sense when reversing
            if (desired_speed < 0.0f) {
                delta_v = -delta_v;
            }

            // Wheel commands
            float v_L = desired_speed - delta_v;
            float v_R = desired_speed + delta_v;

            // Apply minimum speed threshold to each wheel
            if (fabsf(v_L) < 10.0f) v_L = 0.0f;
            if (fabsf(v_R) < 10.0f) v_R = 0.0f;

            // Stop
            if ((v_L == 0.0f) && (v_R == 0.0f)) {
                leftCCR = 0;
                rightCCR = 0;
                LeftIntegral = 0.0f;
                RightIntegral = 0.0f;
            } else {

                // Left Wheel PI Control
                if (v_L >= 0.0f) {
                    GPIO_clearPins(GPIOB, GPIO_PIN8);   // left forward
                } else {
                    GPIO_setPins(GPIOB, GPIO_PIN8);     // left reverse
                }

                if (leftCCR == 0) { //  Used to get wheel started
                    leftCCR = 80;
                }

                float Left_measured_speed = (2000000.0f / enc_counts_avg_L);
                float Lefterror = fabsf(v_L) - Left_measured_speed;
                LeftIntegral += Lefterror;

                leftCCR += (Lefterror * Kp) + (LeftIntegral * Ki);

                if (leftCCR > 720) {    // 90% DC & 10% DC
                    leftCCR = 720;
                } else if (leftCCR < 80) {
                    leftCCR = 80;
                }

                // Right Wheel PI Control
                if (v_R >= 0.0f) {
                    GPIO_clearPins(GPIOB, GPIO_PIN0);   // right forward
                } else {
                    GPIO_setPins(GPIOB, GPIO_PIN0);     // right reverse
                }

                if (rightCCR == 0) {    // Used to get wheel started
                    rightCCR = 80;
                }

                float Right_measured_speed = (2000000.0f / enc_counts_avg_R);
                float Righterror = fabsf(v_R) - Right_measured_speed;
                RightIntegral += Righterror;

                rightCCR += (Righterror * Kp) + (RightIntegral * Ki);

                if (rightCCR > 720) {    // 90% DC & 10% DC
                    rightCCR = 720;
                } else if (rightCCR < 80) {
                    rightCCR = 80;
                }
            }

            Timers_setCCRValue(TIMG8, TIMER_CCR_CCR1, leftCCR);
            Timers_setCCRValue(TIMG8, TIMER_CCR_CCR0, rightCCR);

            Timers_clearCounter(TIMG0);
            flag_100ms = 0;
            /*  // Debug print
            int32_t temp = ((desired_speed - ((2000000.0/enc_counts_avg_L)*100.0)) * Kp)/800;
            printf("%d   %u     %f      %u\r\f",temp, leftCCR, desired_speed,adc0_steer);
            */
        }        
    }   
}      /// End Main Function ///  

